import { layers, namedFlavor } from "@protomaps/basemaps";
import type { FeatureCollection, LineString, MultiPolygon, Point, Polygon } from "geojson";
import type { LayerSpecification, StyleSpecification } from "maplibre-gl";


const sourceId = "san-francisco";

export function createMapStyle(
  archiveUrl: string,
  activityZones: FeatureCollection<Polygon | MultiPolygon>,
  missionPoints: FeatureCollection<Point>,
  activityRoutes: FeatureCollection<LineString>,
): StyleSpecification {
  const flavor = {
    ...namedFlavor("dark"),
    background: "#080d0b",
    earth: "#17211f",
    park_a: "#1d3029",
    park_b: "#244039",
    water: "#123438",
    buildings: "#31413d",
    minor_a: "#33413e",
    minor_b: "#3c4b47",
    major: "#52615d",
    highway: "#63716d",
    roads_label_minor: "#91a39e",
    roads_label_minor_halo: "#18221f",
    roads_label_major: "#bdc9c5",
    roads_label_major_halo: "#18221f",
    ocean_label: "#7faaa9",
    subplace_label: "#d0d9d5",
    subplace_label_halo: "#17211f",
    city_label: "#edf2ef",
    city_label_halo: "#17211f",
    pois: undefined,
  };

  const baseLayers = layers(sourceId, flavor, { lang:"en" }).filter(layer => !["roads_shields","roads_oneway"].includes(layer.id)).map<LayerSpecification>((layer) => {
    if (layer.id !== "buildings") return layer;

    return {
      id: "sf-buildings-3d",
      type: "fill-extrusion",
      source: sourceId,
      "source-layer": "buildings",
      minzoom: 10,
      filter: ["in", ["get", "kind"], ["literal", ["building", "building_part"]]],
      paint: {
        "fill-extrusion-color": [
          "interpolate",
          ["linear"],
          ["coalesce", ["get", "height"], 9],
          0,
          "#202a25",
          18,
          "#34413a",
          45,
          "#536159",
          110,
          "#7d897f",
          220,
          "#a7b1a7",
        ],
        "fill-extrusion-height": [
          "interpolate",
          ["linear"],
          ["zoom"],
          10,
          0,
          12,
          ["coalesce", ["get", "height"], 9],
        ],
        "fill-extrusion-base": ["coalesce", ["get", "min_height"], 0],
        "fill-extrusion-opacity": 0.88,
        "fill-extrusion-vertical-gradient": true,
      },
    };
  });

  return {
    version: 8,
    name: "Local Lore — San Francisco",
    glyphs: "https://protomaps.github.io/basemaps-assets/fonts/{fontstack}/{range}.pbf",
    sprite: new URL("/map-icons/sprite", archiveUrl).href,
    light: {
      anchor: "map",
      color: "#e5eee6",
      intensity: 0.48,
      position: [1.25, 205, 38],
    },
    sources: {
      [sourceId]: {
        type: "vector",
        url: `pmtiles://${archiveUrl}`,
        maxzoom: 14,
        attribution: "© OpenStreetMap contributors · Protomaps",
      },
      "activity-zones": {
        type: "geojson",
        data: activityZones,
      },
      "mission-points": {
        type: "geojson",
        data: missionPoints,
        cluster: true,
        clusterRadius: 34,
        clusterMaxZoom: 13,
        clusterProperties: { activity_count: ["+", ["get", "count"]] },
      },
      "activity-routes": {
        type: "geojson",
        data: activityRoutes,
      },
    },
    layers: [
      ...baseLayers,
      {
        id: "activity-locator",
        type: "circle",
        source: "mission-points",
        filter: ["!", ["has", "point_count"]],
        minzoom: 13,
        paint: {
          "circle-color": ["get", "accent"],
          "circle-radius": ["interpolate", ["linear"], ["zoom"], 13, 18, 15, 22, 18, 27],
          "circle-opacity": ["interpolate", ["linear"], ["zoom"], 13, 0, 14, ["case", [">=", ["get", "outlineAreaM2"], 20000], 0, 0.07], 16, ["case", [">=", ["get", "outlineAreaM2"], 2000], 0, 0.1], 18, ["case", [">=", ["get", "outlineAreaM2"], 160], 0, 0.12]],
          "circle-stroke-color": ["get", "accent"],
          "circle-stroke-width": ["interpolate", ["linear"], ["zoom"], 13, 0.7, 16, 1, 18, 1.25],
          "circle-stroke-opacity": ["interpolate", ["linear"], ["zoom"], 13, 0, 14, ["case", [">=", ["get", "outlineAreaM2"], 20000], 0, 0.3], 16, ["case", [">=", ["get", "outlineAreaM2"], 2000], 0, 0.4], 18, ["case", [">=", ["get", "outlineAreaM2"], 160], 0, 0.45]],
          "circle-pitch-alignment": "viewport",
          "circle-pitch-scale": "viewport",
        },
      },
      {
        id: "route-hover",
        type: "line",
        source: "activity-routes",
        minzoom: 7.8,
        filter: ["==", ["get", "id"], "__none__"],
        layout: { "line-cap": "round", "line-join": "round" },
        paint: { "line-color": ["get", "accent"], "line-width": 3, "line-opacity": 0.7 },
      },
      {
        id: "route-selected",
        type: "line",
        source: "activity-routes",
        minzoom: 7.8,
        filter: ["==", ["get", "id"], "__none__"],
        layout: { "line-cap": "round", "line-join": "round" },
        paint: { "line-color": ["get", "accent"], "line-width": 4, "line-opacity": 0.95 },
      },
      {
        id: "route-hit",
        type: "line",
        source: "activity-routes",
        minzoom: 7.8,
        filter: ["==", ["get", "id"], "__none__"],
        layout: { "line-cap": "round", "line-join": "round" },
        paint: { "line-color": "#ffffff", "line-width": 14, "line-opacity": 0.01 },
      },
      {
        id: "zone-fill",
        type: "fill",
        source: "activity-zones",
        minzoom: 11,
        filter: ["==", ["get", "base"], true],
        paint: {
          "fill-color": ["get", "accent"],
          "fill-opacity": ["interpolate", ["linear"], ["zoom"], 11, 0, 12, ["case", [">=", ["get", "areaM2"], 20000], 0.025, 0], 14, ["case", [">=", ["get", "areaM2"], 1000], 0.065, 0], 16, 0.1, 18, 0.12],
        },
      },
      {
        id: "zone-edge",
        type: "line",
        source: "activity-zones",
        minzoom: 11,
        filter: ["==", ["get", "base"], true],
        paint: {
          "line-color": ["get", "accent"],
          "line-width": ["interpolate", ["linear"], ["zoom"], 11, 0.7, 16, 1.3, 18, 1.4],
          "line-opacity": ["interpolate", ["linear"], ["zoom"], 11, 0, 12, ["case", [">=", ["get", "areaM2"], 20000], 0.25, 0], 14, ["case", [">=", ["get", "areaM2"], 1000], 0.65, 0.1], 16, 0.85, 18, 0.9],
        },
      },
      {
        id: "zone-hover",
        type: "fill",
        source: "activity-zones",
        minzoom: 12.2,
        filter: ["==", ["get", "id"], "__none__"],
        paint: {
          "fill-color": ["get", "accent"],
          "fill-opacity": 0.28,
        },
      },
      {
        id: "zone-hover-edge",
        type: "line",
        source: "activity-zones",
        minzoom: 12.2,
        filter: ["==", ["get", "id"], "__none__"],
        paint: {
          "line-color": ["get", "accent"],
          "line-width": 2,
          "line-opacity": 0.9,
        },
      },
      {
        id: "zone-selected",
        type: "fill",
        source: "activity-zones",
        minzoom: 12.2,
        filter: ["==", ["get", "id"], "__none__"],
        paint: {
          "fill-color": ["get", "accent"],
          "fill-opacity": 0.34,
        },
      },
      {
        id: "zone-selected-edge",
        type: "line",
        source: "activity-zones",
        minzoom: 12.2,
        filter: ["==", ["get", "id"], "__none__"],
        paint: {
          "line-color": ["get", "accent"],
          "line-width": 3.2,
          "line-opacity": 1,
        },
      },
      {
        id: "mission-clusters",
        type: "circle",
        source: "mission-points",
        filter: ["has", "point_count"],
        paint: {
          "circle-color": "#8edcc4",
          "circle-radius": ["step", ["get", "point_count"], 15, 8, 19, 18, 23],
          "circle-stroke-color": "#20312d",
          "circle-stroke-width": 3,
          "circle-opacity": 0.92,
          "circle-pitch-alignment": "map",
          "circle-pitch-scale": "map",
        },
      },
      {
        id: "mission-cluster-count",
        type: "symbol",
        source: "mission-points",
        filter: ["has", "point_count"],
        layout: {
          "text-field": ["to-string", ["get", "activity_count"]],
          "text-font": ["Noto Sans Medium"],
          "text-size": 10,
          "text-allow-overlap": true,
          "text-pitch-alignment": "viewport",
        },
        paint: { "text-color": "#14201d" },
      },
      {
        id: "mission-symbol",
        type: "symbol",
        source: "mission-points",
        filter: ["!", ["has", "point_count"]],
        layout: {
          "icon-image": ["concat", "mission-", ["get", "iconKey"]],
          "icon-size": ["interpolate", ["linear"], ["zoom"], 10, 0.55, 12, 0.72, 14, 0.9, 16, 0.98, 18, 1],
          "icon-allow-overlap": true,
          "icon-ignore-placement": true,
          "icon-anchor": "center",
          "icon-pitch-alignment": "viewport",
          "icon-rotation-alignment": "viewport",
        },
        paint: { "icon-opacity": ["interpolate", ["linear"], ["zoom"], 9, 0.5, 12, 0.9, 14, 1] },
      },
      {
        id: "mission-place-count",
        type: "symbol",
        source: "mission-points",
        filter: ["all", ["!", ["has", "point_count"]], [">", ["get", "count"], 1]],
        layout: {
          "text-field": ["to-string", ["get", "count"]],
          "text-font": ["Noto Sans Medium"],
          "text-size": 11,
          "text-offset": [1.25, -1.1],
          "text-allow-overlap": true,
          "text-pitch-alignment": "viewport",
        },
        paint: { "text-color": "#edf2ef", "text-halo-color": "#14201d", "text-halo-width": 3 },
      },
      {
        id: "mission-hover",
        type: "circle",
        source: "mission-points",
        filter: ["==", ["get", "id"], "__none__"],
        paint: {
          "circle-color": "rgba(0,0,0,0)",
          "circle-radius": ["interpolate", ["linear"], ["zoom"], 10.2, 9, 13, 13, 16, 17],
          "circle-stroke-color": ["get", "accent"],
          "circle-stroke-width": 2,
          "circle-stroke-opacity": 0.82,
          "circle-pitch-alignment": "viewport",
          "circle-pitch-scale": "viewport",
        },
      },
      {
        id: "mission-selected",
        type: "circle",
        source: "mission-points",
        filter: ["==", ["get", "id"], "__none__"],
        paint: {
          "circle-color": "rgba(0,0,0,0)",
          "circle-radius": ["interpolate", ["linear"], ["zoom"], 10.2, 11, 13, 16, 16, 20],
          "circle-stroke-color": ["get", "accent"],
          "circle-stroke-width": 3,
          "circle-opacity": 1,
          "circle-pitch-alignment": "viewport",
          "circle-pitch-scale": "viewport",
        },
      },
      {
        id: "mission-hit",
        type: "circle",
        source: "mission-points",
        filter: ["!", ["has", "point_count"]],
        paint: {
          "circle-color": "#ffffff",
          "circle-radius": 22,
          "circle-opacity": 0.01,
        },
      },
    ],
  };
}
